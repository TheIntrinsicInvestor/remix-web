"""
Olivia Dean -- Dive -- Late-Night Neo-Soul restyle
Recipe: -4 semitones global pitch shift; vocal processed to sit in male register.
Brief generated by Gemini 4.2 after listening to all stems.
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # repo root
from remixkit import *

# ─── PARAMS ──────────────────────────────────────────────────────────────────
SRC        = r"input/Olivia Dean - Dive.wav"
SHIFT      = -4             # semitones (all stems)
LIMIT_DB   = -1.0           # master limiter
OUTPUT_TAG = "late_night_neo_soul"
# ─────────────────────────────────────────────────────────────────────────────

print("=== Separating stems ===")
stems_paths = separate(SRC)
key = detect_key(SRC)
bpm = detect_bpm(SRC)
print(f"Key: {key}  BPM: {bpm}")

print("\n=== Loading all stems ===")
stems = {}
sr, sub = None, "PCM_24"
for name, path in stems_paths.items():
    audio_fm, _sr, _sub = load(path)
    if sr is None:
        sr, sub = _sr, _sub
    stems[name] = to_chanmajor(audio_fm)
print(f"sr={sr}  stems={list(stems)}")

# ─── Global pitch shift (-4 semitones) ───────────────────────────────────────
print(f"\n=== Pitch shifting all stems {SHIFT} semitones ===")
stems = {n: pitch_shift(a, sr, SHIFT) for n, a in stems.items()}

# ─── Per-stem processing ──────────────────────────────────────────────────────

print("\n=== Processing vocals ===")
# HPF rumble, tame chesty 200 Hz, restore articulation at 5k, add air at 8k
stems["vocals"] = eq(stems["vocals"], sr,
    hpf=100,
    bands=[[200, -3.5, 0.8], [5000, 2.5, 1.0], [8000, 2.0, 0.5]])
# Fast comp to keep transient detail forward
stems["vocals"] = compress(stems["vocals"], sr,
    threshold_db=-18, ratio=4, attack_ms=5, release_ms=80)
# Tight plate reverb — acoustic cue to mask pitch-shift artifacts
stems["vocals"] = reverb(stems["vocals"], sr,
    room_size=0.35, wet_level=0.15, dry_level=0.85, damping=0.5)

print("\n=== Processing drums ===")
# Restore snap lost from downshift; saturation for transient bite
stems["drums"] = eq(stems["drums"], sr,
    hpf=40,
    bands=[[6000, 3.0, 0.5]])
stems["drums"] = saturate(stems["drums"], sr, drive_db=3)
stems["drums"] = gain(stems["drums"], db=1.0)

print("\n=== Processing bass ===")
# Remove unusable sub-rumble; harmonics to keep bass audible on small speakers
stems["bass"] = eq(stems["bass"], sr,
    hpf=35,
    bands=[[180, -2.0, 0.8]])
stems["bass"] = saturate(stems["bass"], sr, drive_db=2.5)
stems["bass"] = gain(stems["bass"], db=-2.0)

print("\n=== Processing guitar ===")
# HPF out of vocal mud zone; chorus smears 6s separation artifacts
stems["guitar"] = eq(stems["guitar"], sr, hpf=150)
stems["guitar"] = chorus(stems["guitar"], sr, rate_hz=0.5, depth=0.3)
stems["guitar"] = gain(stems["guitar"], db=-1.5)

print("\n=== Processing piano ===")
# Thin it out so it doesn't mask vocal fundamentals
stems["piano"] = eq(stems["piano"], sr,
    hpf=200,
    bands=[[300, -2.5, 0.8]])
stems["piano"] = reverb(stems["piano"], sr,
    room_size=0.45, wet_level=0.20, dry_level=0.80)
stems["piano"] = gain(stems["piano"], db=-1.5)

print("\n=== Processing other (horns) ===")
# Bandpass into lo-fi background texture; pull well back
stems["other"] = eq(stems["other"], sr, hpf=300, lpf=4000)
stems["other"] = gain(stems["other"], db=-3.0)

# ─── Bounce + save ───────────────────────────────────────────────────────────
print("\n=== Bouncing mix ===")
mix_cm = bounce(stems, sr, limit_db=LIMIT_DB)
fname = name_output("Dive", key, bpm, OUTPUT_TAG, "mix")
save(to_framemajor(mix_cm), sr, f"output/{fname}", sub)
print(f"\nSaved: output/{fname}")
